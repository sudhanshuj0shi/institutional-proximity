/**
 * Minimal auto-escaping HTML templating. Every interpolated value is escaped unless it is
 * already a SafeHtml (produced by html`` or the explicit raw() escape hatch).
 */
export class SafeHtml {
  constructor(public readonly value: string) {}
  toString() { return this.value; }
}

const ESC: Record<string, string> = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
export function escapeHtml(s: string): string {
  return s.replace(/[&<>"']/g, (c) => ESC[c] ?? c);
}

type Value = SafeHtml | string | number | boolean | null | undefined | Value[];

function render(v: Value): string {
  if (v === null || v === undefined || v === false) return "";
  if (Array.isArray(v)) return v.map(render).join("");
  if (v instanceof SafeHtml) return v.value;
  return escapeHtml(String(v));
}

export function html(strings: TemplateStringsArray, ...values: Value[]): SafeHtml {
  let out = "";
  strings.forEach((s, i) => {
    out += s;
    if (i < values.length) out += render(values[i] as Value);
  });
  return new SafeHtml(out);
}

/** Only for markup generated by this codebase — never for user or database content. */
export function raw(s: string): SafeHtml { return new SafeHtml(s); }

/** Safe href: only http(s) or site-relative paths survive; anything else becomes '#'. */
export function safeHref(u: string | null | undefined): string {
  if (!u) return "#";
  if (u.startsWith("/") && !u.startsWith("//")) return u;
  try {
    const p = new URL(u);
    return p.protocol === "https:" || p.protocol === "http:" ? p.toString() : "#";
  } catch {
    return "#";
  }
}

/** JSON for embedding in <script type="application/json">: escapes < so it can't close the tag. */
export function jsonForScript(data: unknown): SafeHtml {
  return new SafeHtml(JSON.stringify(data).replace(/</g, "\\u003c").replace(/\u2028/g, "\\u2028").replace(/\u2029/g, "\\u2029"));
}
